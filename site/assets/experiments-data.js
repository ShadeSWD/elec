/* experiments-data.js — книжка опытов электронного конструктора.
 *
 * Каждый опыт — объект:
 *   id       — номер (он же адрес: builder#exp=<id>);
 *   sec      — раздел книжки;
 *   title    — название;
 *   task     — что собрать и что измерить (HTML);
 *   hint     — подсказка-врезка (HTML, необязательно);
 *   preset() — схема, с которой опыт открывается (иногда пустая или неполная);
 *   solution() — схема, которая ДОЛЖНА пройти проверку (нужна тестам);
 *   wrong()  — схема, которая проверку пройти НЕ должна (нужна тестам);
 *   check(c) — автопроверка: массив { ok, text };
 *   question / answer — вопрос на понимание и ответ;
 *   why      — короткое объяснение «почему так» (показывается после зачёта).
 *
 * Контекст проверки c (см. parts.js → makeCtx):
 *   c.count('R')            — сколько деталей такого вида на поле;
 *   c.val('R','R',0)        — параметр i-й детали;
 *   c.meter('AM',0)         — показание i-го амперметра (VM, WM — так же);
 *   c.elem('R',0)           — результат расчёта для детали: постоянный ток
 *                             {u,i,p}; переменный {U,I,P,Q,S,pf,phU,phI};
 *   c.rms('R',0)            — действующие значения в переходном расчёте;
 *   c.warn                  — предупреждения решателя;
 *   c.expect(текст, получилось, ожидается, допуск, ед.) → {ok, text};
 *   c.ok(условие, текст)    → {ok, text}.
 *
 * Схема записывается помощником S([...]): каждая деталь — [вид, x, y, ось,
 * переворот, параметры]. Ось 'h' (вправо) или 'v' (вниз); переворот 1 меняет
 * местами выводы.
 */
